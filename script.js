function setLanguage(language, remember = true) {
  const lang = language === 'zh' ? 'zh' : 'en';
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  textNodes.forEach((node) => {
    const source = originalText.get(node);
    const key = source.trim();
    const value = lang === 'zh' && Object.prototype.hasOwnProperty.call(translations, key) ? translations[key] : key;
    node.nodeValue = source.replace(key, value);
  });
  document.title = lang === 'zh' ? (titleTranslations[originalTitle] || originalTitle) : originalTitle;
  languageButton.textContent = lang === 'zh' ? 'EN' : '中文';
  languageButton.setAttribute('aria-label', lang === 'zh' ? 'Switch to English' : '切换到中文');
  languageButton.dataset.language = lang;
  if (remember) {
    try { localStorage.setItem('ctc-atlas-language', lang); } catch (_) { /* Privacy mode */ }
  }
}

